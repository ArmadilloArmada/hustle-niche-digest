from __future__ import annotations

import os
from datetime import date, datetime, timezone

from niche_digest.fetch import FeedItem


def _fmt_date(value: datetime | None) -> str:
    if value is None:
        return "n/a"
    return value.astimezone(timezone.utc).strftime("%Y-%m-%d")


def draft_template(niche_name: str, items: list[FeedItem], issue_date: date) -> str:
    bullets: list[str] = []
    for item in items:
        link = f" ([link]({item.link}))" if item.link else ""
        snippet = item.summary[:180] + ("…" if len(item.summary) > 180 else "")
        bullets.append(
            f"- **{item.source} — {item.title}** "
            f"(_published {_fmt_date(item.published)}_){link}\n"
            f"  {snippet}"
        )
    bullet_block = "\n".join(bullets) if bullets else "- _(no items this run)_"
    return f"""# {niche_name}

**Issue date:** {issue_date.isoformat()}  
**Status:** draft — human approve before send  
**Draft mode:** template (no `OPENAI_API_KEY`)

## Intro

Here is this week's roundup of notable releases and changelogs across indie and SaaS
developer tools. Skim the bullets, then edit voice before publishing.

## Digest

{bullet_block}

## Sources

Public RSS/Atom feeds only. Do not paste copyrighted release notes verbatim into a
paid product without review. Prefer short fair-use summaries + links to the original posts.

---
_Generated by hustle-niche-digest. No email was sent._
"""


def draft_with_openai(niche_name: str, items: list[FeedItem], issue_date: date) -> str:
    from openai import OpenAI

    client = OpenAI()
    catalog = "\n".join(
        f"- source={item.source}; title={item.title}; date={_fmt_date(item.published)}; "
        f"url={item.link}; summary={item.summary[:240]}"
        for item in items
    )
    prompt = f"""You write a short niche newsletter digest for indie/SaaS developer tools.

Niche: {niche_name}
Issue date: {issue_date.isoformat()}

Write Markdown with:
1) a 2–3 sentence intro
2) 5–8 bullets (use the provided items; do not invent releases)
3) each bullet: product name, what changed, why it matters, and the source URL
4) a one-line compliance footer reminding the editor to avoid long verbatim quotes

Items:
{catalog}
"""
    response = client.chat.completions.create(
        model=os.environ.get("OPENAI_MODEL", "gpt-4o-mini"),
        messages=[
            {
                "role": "system",
                "content": "You draft concise changelog digests. Never invent products or links.",
            },
            {"role": "user", "content": prompt},
        ],
        temperature=0.4,
    )
    body = (response.choices[0].message.content or "").strip()
    return (
        f"# {niche_name}\n\n"
        f"**Issue date:** {issue_date.isoformat()}  \n"
        f"**Status:** draft — human approve before send  \n"
        f"**Draft mode:** openai\n\n"
        f"{body}\n\n"
        f"---\n_Generated by hustle-niche-digest. No email was sent._\n"
    )


def draft_digest(niche_name: str, items: list[FeedItem], issue_date: date | None = None) -> str:
    issue = issue_date or date.today()
    if os.environ.get("OPENAI_API_KEY"):
        try:
            return draft_with_openai(niche_name, items, issue)
        except Exception as exc:  # noqa: BLE001
            print(f"Warning: OpenAI draft failed ({exc}); falling back to template.")
    return draft_template(niche_name, items, issue)
